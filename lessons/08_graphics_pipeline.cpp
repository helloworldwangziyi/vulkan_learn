// ===========================================================================
// 第八课：图形管线（Graphics Pipeline）—— 全教程最厚的一课
//
// 新增内容：
//   createRenderPass()       —— 描述"渲染目标怎么用"（附件、子通道、依赖）
//   createGraphicsPipeline() —— 装配整条管线：着色器→光栅化→混合
//   readFile()/createShaderModule() —— 加载编译好的 SPIR-V 字节码
//
// 知识点：
//   * 管线是不可变的大状态机：创建后几乎不能改，想换状态就重建
//   * SPIR-V 是 Vulkan 唯一的着色器语言：.vert/.frag 由 glslc 离线编译
//     （改着色器后跑 shaders\build.cmd 重新生成 .spv）
//   * 渲染通道（Render Pass）先于管线创建，管线要引用它
//   * 视口/裁剪设为"动态状态"，录制命令时再给具体值
// ===========================================================================
